		// Use jQuery document ready wrapper and the Bootstrap modal event
		$(document).ready(function () {
			$('#exampleModal').on('show.bs.modal', function (event) {

				// 1. Get the button that triggered the modal
				var $button = $(event.relatedTarget);

				// 2. Extract ALL product data from the button's data attributes
				var title = $button.data('title') || 'Product Title Missing';
				var price = $button.data('price') || 'PKR 0.00';
				var oldPrice = $button.data('old-price'); // Can be null/undefined
				var imageSrc = $button.data('image') || 'images/products/placeholder.png';
				var sku = $button.data('sku') || 'N/A';
				var category = $button.data('category') || 'Uncategorized';
				var tags = $button.data('tags') || 'General';
				var description = $button.data('desc') || 'No detailed description provided for this product.';
				var rating = $button.data('rating') || '0.0';

				// 3. Select the modal and its content elements
				var $modal = $(this);

				// 4. Update the modal's text content
				$modal.find('#modal-title').text(title);
				$modal.find('#modal-description').text(description);
				$modal.find('#modal-sku').text(sku);
				$modal.find('#modal-category').text(category);
				$modal.find('#modal-tags').text(tags);
				$modal.find('#modal-rating').text(rating + ' Rating');

				// 5. Update Price and Sale Badge logic (FIXED LOGIC)
				var $currentPriceElement = $modal.find('#modal-price-current');
				var $oldPriceElement = $modal.find('#modal-old-price');
				var $badgeElement = $modal.find('#modal-badge');

				if (oldPrice) {
					// If oldPrice exists, set the current price and the old price inside the <del> tag
					$currentPriceElement.text(price + ' ');
					$oldPriceElement.text(oldPrice); // Just set the text inside the <del>
					$badgeElement.text('SALE');
					$badgeElement.removeClass('bg-light').addClass('bg-secondary');
				} else {
					// If no oldPrice, only display the current price and clear the old price tag content
					$currentPriceElement.text(price);
					$oldPriceElement.empty();
					$badgeElement.text('NEW');
					$badgeElement.removeClass('bg-secondary').addClass('bg-light'); // Use a light badge for NEW
				}

				// 6. Update the Image source and link
				$modal.find('#modal-main-image').attr('src', imageSrc);
				$modal.find('#modal-image-link').attr('href', imageSrc).attr('data-src', imageSrc);

			});
		});
